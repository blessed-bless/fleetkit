def scan_text(value: str) -> list:
    findings = []
    for fn in INSPECTORS:
        hit = fn(value)
        if hit is not None:
            findings.append(hit)
    findings.sort(key=lambda f: f.score, reverse=True)
    return findings


def any_suspicious(value: str, *, min_score: int = 3) -> bool:
    return any(f.score >= min_score for f in scan_text(value))
